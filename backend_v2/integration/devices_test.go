func TestDevices_List_FilterByCustomer(t *testing.T) {
	cleanDB(t)
	cust1ID, cust1Token := createCustomer(t, "ListD C1", "listd.c1@test.com", "93500050", "560550")
	_, cust2Token := createCustomer(t, "ListD C2", "listd.c2@test.com", "93500051", "560551")
	createDevice(t, cust1ID, "C1 AC", cust1Token)
	resp := makeRequest(t, "GET", "/api/customeraircondevices/?customerId="+cust1ID, nil, cust2Token)
	require.Equal(t, http.StatusOK, resp.StatusCode)
	var body []interface{}
	decodeBody(t, resp, &body)
	require.Len(t, body, 1)
	m := body[0].(map[string]interface{})
	assert.Equal(t, cust1ID, m["customerId"])
}

