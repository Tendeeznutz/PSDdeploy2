func TestDevices_Create_Valid(t *testing.T) {
	cleanDB(t)
	custID, custToken := createCustomer(t, "Dev Alice", "dev.alice@test.com", "93500001", "560501")
	resp := makeRequest(t, "POST", "/api/customeraircondevices/", map[string]interface{}{
		"customerId": custID, "airconName": "Living Room AC",
		"numberOfUnits": 2, "airconType": "daikin",
	}, custToken)
	require.Equal(t, http.StatusCreated, resp.StatusCode)
	var body map[string]interface{}
	decodeBody(t, resp, &body)
	assert.NotEmpty(t, body["id"])
}

